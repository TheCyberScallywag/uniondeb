"""Generate synthetic CyberScallywags UK communications traffic with ground truth.

    uv run python uniondeb synth generate --out traffic/run-001 \\
        --employees 150 --externals 450 --days 45 --start 2026-09-01

Output (everything is SYNTHETIC; see README.SYNTHETIC.txt in the run folder):

  data/normal/<dataset>/date=YYYY-MM-DD/part-NNNN.{jsonl,csv,parquet}   background traffic
  data/insider_dealing/<dataset>/…                                     scenario records only
  data/drug_trafficking/<dataset>/…                                    scenario records only
  data/adversarial/messages/…                                          tagger-defeating fixtures
     (--blend writes scenario records into the normal partitions instead)
  roster/people.csv, roster/devices.jsonl                              who owns which identifiers
  config/triggers.txt, config/code_of_ethics.DRAFT.md                  inputs for the tagging agents
  ground_truth/labels.csv          expected tag, clauses, typology and subjects for every record
  ground_truth/expected_errors.csv injected faults the ingest agent must send to human review
  ground_truth/scenarios.json      actors, timeline and hidden links per scenario
  manifest.json                    every file with sha256, rows, format, dialect (provenance seed)

Implements: UND-012, UND-043
"""

import argparse
import csv
import json
import random
import time
from collections import defaultdict
from datetime import UTC, date, datetime, timedelta
from pathlib import Path

from uniondeb.core.schemas import SCHEMA_VERSION

from . import content as C
from .directory import Directory
from .scenarios import Labelled, NormalConfig, adversarial, drug_trafficking, insider_dealing, normal_day
from .writer import Sink, WriteOptions

SYNTHETIC_NOTICE = """THIS FOLDER CONTAINS SYNTHETIC TEST DATA.

Every person, phone number, identifier, company, ticker and event in it is fictional,
generated by uniondeb.synth for testing CyberScallywags UK's conduct-monitoring platform.
Numbers use Ofcom drama ranges; IMSIs the ITU test network; IPs documentation ranges.
The insider-dealing and drug-supply scenarios are training fixtures. They are not
evidence about, or allegations against, any real person.
"""


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", type=Path, default=Path("traffic/run"))
    p.add_argument("--start", type=date.fromisoformat, default=date(2026, 9, 1))
    p.add_argument("--days", type=int, default=30)
    p.add_argument("--employees", type=int, default=120)
    p.add_argument("--externals", type=int, default=360)
    p.add_argument("--seed", type=int, default=1646)
    p.add_argument("--msgs", type=float, default=10.0, help="messages per employee per weekday")
    p.add_argument("--calls", type=float, default=4.0, help="calls per employee per weekday")
    p.add_argument("--handoffs", type=float, default=0.12, help="hand-off conversations per employee per weekday")
    p.add_argument("--benign-trigger-rate", type=float, default=0.03)
    p.add_argument("--format", choices=("mixed", "jsonl", "csv", "parquet"), default="mixed")
    p.add_argument("--rows-per-file", type=int, default=5000)
    p.add_argument("--messy-share", type=float, default=0.3, help="share of files in a source-system dialect")
    p.add_argument("--error-rate", type=float, default=0.002, help="share of normal rows with an injected fault")
    p.add_argument("--scenarios", default="insider_dealing,drug_trafficking,adversarial")
    p.add_argument("--blend", action="store_true", help="mix scenario records into the normal partitions")
    return p


def main(argv: list[str] | None = None) -> dict:
    a = build_parser().parse_args(argv)
    t0 = time.time()
    rng = random.Random(a.seed)
    d = Directory(seed=a.seed, employees=a.employees, externals=a.externals)
    sink = Sink(
        WriteOptions(
            out=a.out,
            formats=a.format,
            rows_per_file=a.rows_per_file,
            messy_share=a.messy_share,
            error_rate=a.error_rate,
            seed=a.seed,
        )
    )
    wanted = {s.strip() for s in a.scenarios.split(",") if s.strip()}

    # Scenarios first (drug_trafficking adds burner devices to the directory)
    results = []
    if "insider_dealing" in wanted:
        results.append(insider_dealing(rng, d, a.start, a.days))
    if "drug_trafficking" in wanted:
        used = {v["person_id"] for r in results for v in r.actors.values() if isinstance(v, dict) and "person_id" in v}
        results.append(drug_trafficking(rng, d, a.start, a.days, exclude=used))
    if "adversarial" in wanted:
        actors = {r["person_id"] for r in d.roster_rows()} & set(_actor_ids(results))
        results.append(adversarial(d, a.start, a.days, a.seed, exclude=actors))

    scenario_by_day: dict[str, dict[str, list[Labelled]]] = defaultdict(lambda: defaultdict(list))
    for res in results:
        if res.name == "adversarial":
            continue  # written last, so the files of every other scenario are unchanged by it
        for rec in res.records:
            scenario_by_day[rec.at.date().isoformat()][rec.dataset].append(rec)

    cfg = NormalConfig(a.msgs, a.calls, a.handoffs, benign_trigger_rate=a.benign_trigger_rate)
    counts: dict[str, int] = defaultdict(int)
    for i in range(a.days):
        day = a.start + timedelta(days=i)
        key = day.isoformat()
        buckets: dict[str, list[Labelled]] = defaultdict(list)
        for rec in normal_day(rng, d, day, cfg):
            buckets[rec.dataset].append(rec)
        for ds_name, recs in scenario_by_day.pop(key, {}).items():
            if a.blend:
                buckets[ds_name].extend(recs)
            else:
                by_scn: dict[str, list[Labelled]] = defaultdict(list)
                for r in recs:
                    by_scn[r.scenario].append(r)
                for scn, rs in by_scn.items():
                    sink.write_partition(scn, ds_name, key, rs)
                    counts[scn] += len(rs)
        for ds_name, recs in buckets.items():
            sink.write_partition("normal", ds_name, key, recs)
            counts["normal" if not a.blend else "blended"] += len(recs)
    # scenario records that fall outside the window (e.g. +1 day after the end)
    for key, per_ds in sorted(scenario_by_day.items()):
        for ds_name, recs in per_ds.items():
            by_scn: dict[str, list[Labelled]] = defaultdict(list)
            for r in recs:
                by_scn[r.scenario].append(r)
            for scn, rs in by_scn.items():  # one write per partition, never one per record
                sink.write_partition(scn, ds_name, key, rs)
                counts[scn] += len(rs)

    late: dict[str, list[Labelled]] = defaultdict(list)
    for res in results:
        if res.name == "adversarial":
            for rec in res.records:
                late[rec.at.date().isoformat()].append(rec)
    for key, recs in sorted(late.items()):
        sink.write_partition("adversarial", "messages", key, recs)
        counts["adversarial"] += len(recs)

    _write_side_files(a, d, sink, results)
    summary = {
        "run": a.out.name,
        "generated_at": datetime.now(UTC).isoformat(),
        "seconds": round(time.time() - t0, 1),
        "schema_version": SCHEMA_VERSION,
        "synthetic": True,
        "seed": a.seed,
        "start": a.start.isoformat(),
        "days": a.days,
        "employees": a.employees,
        "externals": a.externals,
        "records": dict(counts),
        "files": len(sink.manifest),
        "bytes": sum(f["bytes"] for f in sink.manifest),
        "expected_tags": _tally(sink.labels, "expected_tag"),
        "injected_errors": len(sink.errors),
    }
    (a.out / "manifest.json").write_text(json.dumps({**summary, "files": sink.manifest}, indent=1) + "\n")
    print(json.dumps(summary, indent=1))
    return summary


def _actor_ids(results) -> list[str]:
    """Every roster id named anywhere in the scenarios' actors, so fixtures never reuse a scenario actor."""
    found: list[str] = []

    def walk(v) -> None:
        if isinstance(v, dict):
            for x in v.values():
                walk(x)
        elif isinstance(v, list):
            for x in v:
                walk(x)
        elif isinstance(v, str):
            found.append(v)

    for r in results:
        walk(r.actors)
    return found


def _tally(rows: list[dict], key: str) -> dict[str, int]:
    out: dict[str, int] = defaultdict(int)
    for r in rows:
        out[r[key]] += 1
    return dict(out)


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as fh:
        if not rows:
            return
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def _write_side_files(a, d: Directory, sink: Sink, results) -> None:
    out: Path = a.out
    (out / "README.SYNTHETIC.txt").write_text(SYNTHETIC_NOTICE)
    _write_csv(out / "roster" / "people.csv", d.roster_rows())
    with (out / "roster" / "devices.jsonl").open("w") as fh:
        for dev in d.devices:
            fh.write(dev.model_dump_json() + "\n")
    (out / "config").mkdir(parents=True, exist_ok=True)
    (out / "config" / "triggers.txt").write_text(
        "# Example trigger list (one phrase per line, case-insensitive, whole-word).\n"
        "# CyberScallywags UK owns and maintains the real list.\n" + "\n".join(C.TRIGGERS) + "\n"
    )
    (out / "config" / "code_of_ethics.DRAFT.md").write_text(
        "# Code of ethics — DRAFT placeholder\n\n> Replace with CyberScallywags UK's adopted code before use.\n\n"
        + "\n".join(f"- **{k}** {v}" for k, v in C.CODE_OF_ETHICS_DRAFT.items())
        + "\n"
    )
    _write_csv(out / "ground_truth" / "labels.csv", sink.labels)
    _write_csv(out / "ground_truth" / "expected_errors.csv", sink.errors)
    (out / "ground_truth" / "scenarios.json").write_text(
        json.dumps(
            [
                {
                    "name": r.name,
                    "records": len(r.records),
                    "actors": r.actors,
                    "timeline": r.timeline,
                    "hidden_links": r.hidden_links,
                    "tags": _tally([{"t": x.tag} for x in r.records], "t"),
                }
                for r in results
            ],
            indent=1,
            ensure_ascii=False,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
