# ───────────────────────────── spelling + normalisation ─────────────────────────────
_NON_ALNUM = re.compile(r"[^a-z0-9]")


def normalize(key: Any) -> str:
    """'Caller I.M.E.I' → 'callerimei'; 'Siân' → 'sian'; 'imeiNumber' → 'imeinumber'."""
    s = unicodedata.normalize("NFKD", str(key)).encode("ascii", "ignore").decode()
    return _NON_ALNUM.sub("", s.lower())


def spellings(snake: str) -> list[str]:
    """call_id → call_id, callId, CallId, CALL_ID, call-id."""
    parts = snake.split("_")
    camel = parts[0] + "".join(p.title() for p in parts[1:])
    return list(dict.fromkeys([snake, camel, camel[:1].upper() + camel[1:], snake.upper(), snake.replace("_", "-")]))


def aka(canonical: str, *extra: str) -> AliasChoices:
    """``AliasChoices`` for a canonical field: its own name plus every synonym spelling."""
    names = [canonical, *SYNONYMS.get(canonical, ()), *extra]
    return AliasChoices(*dict.fromkeys(s for n in names for s in spellings(n)))


def _choices(alias: Any) -> Iterable[str]:
    if isinstance(alias, str):
        yield alias
    elif isinstance(alias, AliasChoices):
        for c in alias.choices:
            if isinstance(c, str):
                yield c
            elif isinstance(c, AliasPath) and c.path and isinstance(c.path[0], str):
                yield c.path[0]


# ───────────────────────────── audit trail ──────────────────────────────────────────
@dataclass(slots=True)
class ResolutionReport:
    keys: list[tuple[str, str, str]] = field(default_factory=list)  # (model, input key, canonical field)
    values: list[tuple[str, str, Any, Any]] = field(default_factory=list)  # (model.field, input, canonical)
    unknown: list[tuple[str, str]] = field(default_factory=list)  # (model, input key)

    def summary(self) -> dict[str, Any]:
        return {
            "keys_resolved": [f"{m}: {k!r} → {c}" for m, k, c in self.keys],
            "values_resolved": [f"{f}: {i!r} → {c!r}" for f, i, c in self.values],
            "unknown_keys": [f"{m}: {k!r}" for m, k in self.unknown],
        }


def _report(info: ValidationInfo | None) -> ResolutionReport | None:
    ctx = info.context if info is not None else None
    return ctx.get("report") if isinstance(ctx, dict) else None


# ───────────────────────────── layer 2: models that resolve their own keys ──────────
class Resolving(BaseModel):
    """Base model: input keys are matched to fields by normalised alias, then validated by name."""

    _key_lookup: ClassVar[dict[str, str]] = {}
    _ignore_keys: ClassVar[frozenset[str]] = frozenset()  # e.g. computed fields echoed back in input

    @classmethod
    def __pydantic_init_subclass__(cls, **kwargs: Any) -> None:
        super().__pydantic_init_subclass__(**kwargs)
        lookup: dict[str, str] = {}
        for name, f in cls.model_fields.items():
            for key in {normalize(name), *(normalize(a) for a in _choices(f.validation_alias))}:
                if (other := lookup.get(key)) and other != name:
                    raise TypeError(f"{cls.__name__}: alias {key!r} is ambiguous between {other!r} and {name!r}")
                lookup[key] = name
        cls._key_lookup = lookup
        cls._ignore_keys = frozenset(normalize(n) for n in cls.model_computed_fields)

    @model_validator(mode="before")
    @classmethod
    def _resolve_keys(cls, data: Any, info: ValidationInfo) -> Any:
        if not isinstance(data, dict):
            return data
        report = _report(info)
        out: dict[str, Any] = {}
        for key, value in data.items():
            nk = normalize(key)
            name = cls._key_lookup.get(nk)
            if name is None:
                if report is not None and nk not in cls._ignore_keys:
                    report.unknown.append((cls.__name__, str(key)))
                continue  # unknown keys are dropped (and reported), never guessed
            if name in out and out[name] != value:
                raise ValueError(f"conflicting values for {name!r}: {out[name]!r} vs {value!r} (from {key!r})")
            out[name] = value
            if report is not None and key != name:
                report.keys.append((cls.__name__, str(key), name))
        return cls._after_resolve(out)

    @classmethod
    def _after_resolve(cls, data: dict[str, Any]) -> dict[str, Any]:
        """Hook for derivations that need canonical keys (runs right after resolution)."""
        return data


# ───────────────────────────── layer 3: value synonyms ──────────────────────────────
def one_of[E: Enum](enum_cls: type[E], synonyms: dict[E, tuple[str, ...]] | None = None) -> BeforeValidator:
    """BeforeValidator mapping value variants (by normalised text) onto members of ``enum_cls``."""
    table: dict[str, E] = {}
    for m in enum_cls:
        table[normalize(m.value)] = m
        table[normalize(m.name)] = m
    for m, variants in (synonyms or {}).items():
        for v in variants:
            table[normalize(v)] = m

    def resolve(value: Any, info: ValidationInfo) -> Any:
        if isinstance(value, int) and not isinstance(value, bool):
            value = str(value)  # e.g. Q.850 cause code 16 → "16"
        if isinstance(value, str) and not isinstance(value, Enum) and (m := table.get(normalize(value))) is not None:
            if (report := _report(info)) is not None and value != m.value:
                report.values.append((f"{info.config.get('title', '?')}.{info.field_name}", value, m.value))
            return m
        return value

    return BeforeValidator(resolve)


def boolean_of(true: Iterable[str], false: Iterable[str]) -> BeforeValidator:
    """BeforeValidator for booleans that arrive as status codes (e.g. SMPP DLR ``DELIVRD``)."""
    t, f = {normalize(x) for x in true}, {normalize(x) for x in false}

    def resolve(value: Any, info: ValidationInfo) -> Any:
        if isinstance(value, str):
            nv = normalize(value)
            out = True if nv in t else False if nv in f else value
            if out is not value and (report := _report(info)) is not None:
                report.values.append((f"{info.config.get('title', '?')}.{info.field_name}", value, out))
            return out
        return value

    return BeforeValidator(resolve)


def lookup_for(*models: type[Resolving]) -> Callable[[str], str | None]:
    """Normalised key → canonical field across several models (for flat-row prefix splitting)."""
    merged: dict[str, str] = {}
    for m in models:
        merged.update(m._key_lookup)
    return lambda key: merged.get(normalize(key))
