"""Resolve property-name and value variations to canonical definitions with Pydantic aliases.

Feeds from switches, MNOs, SBCs and spreadsheets name the same thing many ways:
``IMEI``, ``imei_number``, ``handsetId``, ``Equipment ID``… This module makes them all
land on one canonical field, in three layers:

1. **Pydantic aliases (source of truth).** Every canonical field gets
   ``validation_alias=AliasChoices(...)`` built from ``SYNONYMS``, in snake, camel,
   Pascal, UPPER and kebab spellings. Plain ``model_validate`` uses these directly.
2. **Normalised key matching.** ``Resolving`` models derive a lookup from *their own*
   alias choices, keyed by ``normalize()`` (case, accents and punctuation removed), so
   ``"Caller I.M.E.I"`` or ``"imei-number"`` still resolve. Two fields that normalise to
   the same key are refused when the class is defined.
3. **Value synonyms.** ``one_of()`` maps value variants (``cell`` → ``mobile``,
   ``DELIVRD`` → ``True``, ``no answer`` → ``missed``) to the canonical enum member.

Pass ``context={"report": ResolutionReport()}`` to ``model_validate`` to see every
mapping that was applied, plus any keys that couldn't be resolved.

Implements: UND-011
"""

