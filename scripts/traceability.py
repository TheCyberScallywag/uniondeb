#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = ["pyyaml>=6"]
# ///
"""Build TRACEABILITY.md: backlog step → issue → branch → commits → code → tests.

Implements: UND-010

Sources, all in the repo, so the matrix is reproducible from any checkout:
  backlog/backlog.yaml        the steps (UND-NNN)
  backlog/issue-map.json      issue numbers (written by scripts/bootstrap_backlog.py)
  git log                     commits whose message carries "Refs: UND-NNN"
  packages/**/*.py            modules whose docstring says "Implements: UND-NNN"
  packages/**/tests/*.py      tests marked "Verifies: UND-NNN" (and tests/ at the root)

    uv run scripts/traceability.py            # rewrite TRACEABILITY.md
    uv run scripts/traceability.py --check    # CI: fail if the file is stale or a commit lacks a Refs trailer
"""

import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "TRACEABILITY.md"
ID = re.compile(r"\bUND-\d{3}\b")


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True).stdout


def commits_by_step() -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    log = git("log", "--all", "--format=%h%x1f%s%x1f%(trailers:key=Refs,valueonly,separator=%x2C)%x1e")
    for rec in filter(None, (r.strip() for r in log.split("\x1e"))):
        sha, subject, refs = (rec.split("\x1f") + ["", ""])[:3]
        for step in sorted(set(ID.findall(refs))):
            out[step].append(f"`{sha}` {subject}")
    return out


def branches_by_step() -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    for b in git("branch", "-a", "--format=%(refname:short)").split():
        m = re.search(r"und-(\d{3})", b)
        if m:
            name = b.removeprefix("origin/")
            step = f"UND-{m.group(1)}"
            if name not in out[step]:
                out[step].append(name)
    return out


def markers(pattern: str, tests: bool) -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    rx = re.compile(pattern + r":\s*((?:UND-\d{3}[,\s]*)+)")
    paths = [*(ROOT / "packages").rglob("*.py"), *(ROOT / "tests").rglob("*.py"), *(ROOT / "scripts").glob("*.py")]
    for path in sorted(paths):
        is_test = "tests" in path.relative_to(ROOT).parts
        if is_test != tests:
            continue
        text = path.read_text(errors="ignore")
        for m in rx.finditer(text):
            for step in ID.findall(m.group(1)):
                rel = path.relative_to(ROOT).as_posix()
                if rel not in out[step]:
                    out[step].append(rel)
    return out


def build() -> str:
    backlog = yaml.safe_load((ROOT / "backlog" / "backlog.yaml").read_text())
    issue_map = (
        json.loads((ROOT / "backlog" / "issue-map.json").read_text())
        if (ROOT / "backlog" / "issue-map.json").exists()
        else {}
    )
    repo = backlog["project"]["repo"]
    commits, branches = commits_by_step(), branches_by_step()
    code, tests = markers("Implements", tests=False), markers("Verifies", tests=True)
    epics = {e["id"]: e for e in backlog["epics"]}

    def issue(key: str) -> str:
        n = issue_map.get(key, {}).get("number")
        return f"[#{n}](https://github.com/{repo}/issues/{n})" if n else "—"

    def status(s: dict) -> str:
        if s.get("owner") == "human":
            return "👤 people task"
        if code.get(s["id"]) and tests.get(s["id"]):
            return "✅ implemented + tested"
        if code.get(s["id"]) or commits.get(s["id"]):
            return "🟡 in progress"
        return "⬜ not started"

    lines = [
        "# Traceability matrix",
        "",
        "_Generated by `scripts/traceability.py` from `backlog/backlog.yaml`, `backlog/issue-map.json`, git "
        "trailers (`Refs: UND-NNN`), code markers (`Implements: UND-NNN`) and test markers (`Verifies: UND-NNN`). "
        "Do not edit by hand._",
        "",
    ]
    totals: dict[str, int] = defaultdict(int)
    for s in backlog["steps"]:
        totals[status(s).split(" ", 1)[1]] += 1
    lines += ["**Summary:** " + " · ".join(f"{k}: {v}" for k, v in totals.items()), ""]
    for eid, e in epics.items():
        steps = [s for s in backlog["steps"] if s["epic"] == eid]
        lines += [
            f"## {eid} — {e['title'].split('—', 1)[-1].strip()} ({issue(eid)})",
            "",
            "| Step | Title | Issue | Status | Branch | Commits | Code | Tests |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for s in steps:

            def cell(items: list[str]) -> str:
                return "<br>".join(items) if items else "—"

            lines.append(
                f"| {s['id']} | {s['title']} | {issue(s['id'])} | {status(s)} | {cell(branches.get(s['id'], []))} | "
                f"{cell(commits.get(s['id'], []))} | {cell([f'`{c}`' for c in code.get(s['id'], [])])} | "
                f"{cell([f'`{t}`' for t in tests.get(s['id'], [])])} |"
            )
        lines.append("")
    return "\n".join(lines)


def check_trailers(base: str) -> list[str]:
    bad = []
    for line in git("log", f"{base}..HEAD", "--format=%h%x1f%s%x1f%(trailers:key=Refs,valueonly)").splitlines():
        sha, subject, refs = (line.split("\x1f") + ["", ""])[:3]
        if not ID.search(refs):
            bad.append(f"{sha} {subject}")
    return bad


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--base", default="origin/main", help="for --check: commits after this must carry Refs trailers")
    a = ap.parse_args()
    text = build()
    if a.check:
        problems = []
        if not OUT.exists() or OUT.read_text() != text:
            problems.append("TRACEABILITY.md is stale: run `uv run scripts/traceability.py` and commit it")
        problems += [f"commit without a 'Refs: UND-NNN' trailer: {c}" for c in check_trailers(a.base)]
        for p in problems:
            print("✗", p)
        return 1 if problems else 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
